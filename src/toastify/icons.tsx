export function DefaultToastIcon({ type }: { type: ToastType }) {
  const badgeClasses = "toastify-badge";

  switch (type) {
    case "loading":
      return (
        <span className={badgeClasses}>
          <LoaderIcon />
        </span>
      );
    case "success":
      return (
        <span className={badgeClasses}>
          <CheckIcon />
        </span>
      );
    case "error":
      return (
        <span className={badgeClasses}>
          <XIcon />
        </span>
      );
    case "warning":
      return (
        <span className={badgeClasses}>
          <WarningIcon />
        </span>
      );
    case "info":
    case "neutral":
    default:
      return (
        <span className={badgeClasses}>
          <InfoIcon />
        </span>
      );
  }
}
